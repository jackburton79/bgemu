void
MovieDecoder::TestExecute(uint8 opcode, const uint8 data[], uint32 size, const char* name)
{
	uint8 *decodingMap = new uint8[1];
	decodingMap[0] = opcode;
	SetDecodingMap(decodingMap, 1);

	MemoryStream stream(data, size);
	const off_t start = stream.Position();
	DecodeDataBlock(&stream, stream.Size());
	if (stream.Position() - start != size) {
		std::cout << "Streaming error: consumed size is different than data size" << std::endl;
		throw std::runtime_error("TestExecute decode error!");
	}
}


void
MovieDecoder::TestFinish(Bitmap* bitmap, const uint8 data[], uint32 dataSize)
{
	int result = memcmp(data, bitmap->Pixels(), dataSize);
	std::cout << "MovieDecoder::TestFinish(opcode 0x" << std::hex;
	std::cout << (int)(fDecodingMap[0] & 0xF) << "): ";
	std::cout << (result ? "FAILURE" : "OK") << std::endl;

	if (result) {
		std::cout << "Data is:" << std::endl;
		DumpData((uint8*)fScratchBuffer->Pixels(), 64);
		std::cout << "should be:" << std::endl;
		DumpData(data, dataSize);
		throw std::runtime_error("TestFinish error!");
	}

	fNewFrame->Release();
	fCurrentFrame->Release();
	fNewFrame = NULL;
	fCurrentFrame = NULL;
}


